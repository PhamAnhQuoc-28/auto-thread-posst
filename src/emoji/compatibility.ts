export function unsupportedEmojiIn(text: string): string[] {
  return unsupportedEmojiUnified.filter(unified => {
    const sequence = String.fromCodePoint(...unified.split('-').map(part => parseInt(part, 16)));
    return text.includes(sequence);
  });
}

export function describeUnsupportedEmoji(text: string): string | null {
  const found = unsupportedEmojiIn(text);
  if (!found.length) return null;
  return `Emoji mới chưa hiển thị đúng trên trình duyệt này (${found.map(item => item.toUpperCase().split('-').map(part => `U+${part}`).join(' ')).join(', ')}). Hãy thay bằng emoji phổ biến trước khi lưu hoặc đăng.`;
}
